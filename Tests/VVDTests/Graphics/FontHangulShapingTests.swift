final class FontHangulShapingTests: XCTestCase {
    func testExplicitFeatureRangeRemainsRelativeToTheCompleteSource() throws {
        var root = URL(fileURLWithPath: #filePath)
        for _ in 0..<4 { root.deleteLastPathComponent() }
        let file = root.appendingPathComponent("Sources/VUI/Resources/Fonts/NotoSansKR/NotoSansKR-VariableFont_wght.ttf")
        let font = try XCTUnwrap(Font(data: Data(contentsOf: file)))
        XCTAssertTrue(font.setVariationCoordinates([0x7767_6874: 100]))
        font.setPointSize(23, dpi: (72, 72))
        let feature = try XCTUnwrap(Font.ShapingFeature(tag: "calt", value: 1, range: 2..<5))
        let shaped = try XCTUnwrap(font.shape("A 가 나 가 나", features: [feature]))
        XCTAssertEqual(shaped.glyphs.map(\.index), [34, 1, 10255, 22481, 11431, 1, 10255, 1, 11431])
        XCTAssertEqual(shaped.glyphs.map(\.sourceRange), (0..<9).map { $0..<($0 + 1) })
        XCTAssertEqual(shaped.glyphs[3].advance.width, 6.44, accuracy: 0.000_001)
        XCTAssertEqual(shaped.glyphs[5].advance.width, 5.06, accuracy: 0.000_001)
        XCTAssertEqual(shaped.glyphs[7].advance.width, 5.06, accuracy: 0.000_001)
    }

