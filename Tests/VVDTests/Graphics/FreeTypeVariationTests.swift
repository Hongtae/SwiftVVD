import FreeType
import XCTest

final class FreeTypeVariationTests: XCTestCase {
    // Keep this guard when replacing the bundled FreeType sources. Matching
    // coordinate readback alone cannot detect stale MVAR metrics. The fixture
    // and all diagnostic faces belong to tests, never library initialization.
    func testMetricsAndCoordinatesRestoreAcrossHistory() throws {
        var handle: FT_Library?
        XCTAssertEqual(FT_Init_FreeType(&handle), 0)
        let library = try XCTUnwrap(handle)
        defer { FT_Done_FreeType(library) }
        try Self.fixture.withUnsafeBufferPointer { bytes in
            func makeFace(index: FT_Long) throws -> FT_Face {
                var face: FT_Face?
                XCTAssertEqual(FT_New_Memory_Face(library, bytes.baseAddress,
                                                FT_Long(bytes.count), index, &face), 0)
                return try XCTUnwrap(face)
            }
            let reused = try makeFace(index: 0)
            defer { FT_Done_Face(reused) }
            let initial = try XCTUnwrap(Self.snapshot(reused))
            XCTAssertEqual(Array(initial.prefix(3)), [1800, -400, 2100])
            // Positive control: the fixture must exercise nonzero MVAR deltas.
            XCTAssertTrue(Self.apply(.design([900, 100]), to: reused))
            let varied = try XCTUnwrap(Self.snapshot(reused))
            XCTAssertEqual(Array(varied.prefix(3)), [1900, -450, 2220])
            // Full, repeated, empty and partial requests also check omitted-axis
            // defaults. Named instance 2 is Heavy; instance 0 clears it.
            let operations: [Operation] = [
                .design([900, 100]), .design([650, 100]), .design([400, 100]),
                .design([100, 100]), .design([]),
                .design([900, 75]), .design([650]),
                .design([900, 75]), .blend([32768]),
                .blend([65536, 0]), .blend([]),
                .named(2), .named(2), .named(0),
                .named(2), .design([650, 100]), .design([]),
                .design([650, 75]), .blend([]), .named(0)
            ]
            for (step, operation) in operations.enumerated() {
                let index: FT_Long
                if case .named = operation { index = 0 }
                else { index = reused.pointee.face_index }
                let fresh = try makeFace(index: index)
                defer { FT_Done_Face(fresh) }
                let label = "step \(step): \(operation)"
                XCTAssertTrue(Self.apply(operation, to: reused), label)
                XCTAssertTrue(Self.apply(operation, to: fresh), label)
                let result = try XCTUnwrap(Self.snapshot(reused), label)
                let reference = try XCTUnwrap(Self.snapshot(fresh), label)
                XCTAssertEqual(result, reference, label)
            }
            XCTAssertEqual(Self.snapshot(reused), initial)
        }
    }

    private enum Operation {
        case design([FT_Fixed])
        case blend([FT_Fixed])
        case named(FT_UInt)
    }

    private static func apply(_ operation: Operation, to face: FT_Face) -> Bool {
        switch operation {
        case .design(let values):
            var coordinates = values.map { $0 * 65536 }
            return coordinates.withUnsafeMutableBufferPointer {
                FT_Set_Var_Design_Coordinates(face, FT_UInt($0.count),
                                             $0.isEmpty ? nil : $0.baseAddress) == 0
            }
        case .blend(var coordinates):
            return coordinates.withUnsafeMutableBufferPointer {
                FT_Set_Var_Blend_Coordinates(face, FT_UInt($0.count),
                                            $0.isEmpty ? nil : $0.baseAddress) == 0
            }
        case .named(let index):
            return FT_Set_Named_Instance(face, index) == 0
        }
    }

    private static func snapshot(_ face: FT_Face) -> [FT_Long]? {
        guard FT_Set_Char_Size(face, 0, 13 * 64, 72, 72) == 0,
              let os2 = FT_Get_Sfnt_Table(face, FT_SFNT_OS2)?
                .assumingMemoryBound(to: TT_OS2.self),
              let post = FT_Get_Sfnt_Table(face, FT_SFNT_POST)?
                .assumingMemoryBound(to: TT_Postscript.self) else { return nil }
        var coordinates = [FT_Fixed](repeating: 0, count: 2)
        var blend = coordinates
        guard FT_Get_Var_Design_Coordinates(face, 2, &coordinates) == 0,
              FT_Get_Var_Blend_Coordinates(face, 2, &blend) == 0 else { return nil }
        let value = face.pointee
        let metrics = value.size.pointee.metrics
        return [
            FT_Long(value.ascender), FT_Long(value.descender), FT_Long(value.height),
            FT_Long(value.underline_position), FT_Long(value.underline_thickness),
            FT_Long(os2.pointee.sTypoAscender), FT_Long(os2.pointee.sTypoDescender),
            FT_Long(os2.pointee.sTypoLineGap), FT_Long(os2.pointee.sxHeight),
            FT_Long(os2.pointee.sCapHeight), FT_Long(post.pointee.underlinePosition),
            FT_Long(post.pointee.underlineThickness),
            metrics.ascender, metrics.descender, metrics.height,
            coordinates[0], coordinates[1], blend[0], blend[1], value.face_index
        ]
    }

